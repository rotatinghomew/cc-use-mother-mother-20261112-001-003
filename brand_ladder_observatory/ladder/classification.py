class LadderClassification:
    stage = STAGE

    def process(self, state: RunState) -> None:
        evaluations = []
        for policy in POLICIES:
            enriched = dict(policy)
            enriched["stage"] = self.stage
            evaluations.append(evaluate_policy(enriched, state.payload, state))
        values = self._domain_values(state)
        state.artifacts[self.stage] = {
            "focus": FOCUS,
            "policy_count": len(POLICIES),
            "failed_count": sum(1 for item in evaluations if item["failed"]),
            "domain_values": values,
            "evidence_hash": stable_json(evaluations)[:240],
        }
        state.set_metric(self.stage + "_coverage", (len(POLICIES) - state.artifacts[self.stage]["failed_count"]) / len(POLICIES))
        state.emit(self.stage, "stage_evaluated", focus=FOCUS, failures=state.artifacts[self.stage]["failed_count"], values=values)
        state.advance(self.stage)

    def _domain_values(self, state: RunState) -> dict[str, Any]:
        records = sequence(get_path(state.payload, "records", []))
        timeline = sequence(get_path(state.payload, "timeline", []))
        links = sequence(get_path(state.payload, "links", []))
        numeric = [number(item.get("value", item.get("amount", 0))) for item in records if isinstance(item, dict)]
        return self._classify(state, records, timeline, links, numeric)

    def _classify(self, state: RunState, records: list[Any], timeline: list[Any], links: list[Any], numeric: list[float]) -> dict[str, Any]:
        score = number(get_path(state.payload,'attributes.risk_score',50),50)
        level = 'regional' if score >= 85 else 'independent' if score >= 65 else 'oem' if score >= 40 else 'unbranded'
        return {'score':score,'level':level,'upgrade_gap': max(0,85-score)}
